// Nationalité suggérée à partir du libellé "pays de naissance" choisi (ex.
// "🇲🇱 Mali") et du sexe déjà renseigné ('femme'/'homme') — reste une simple
// suggestion : le champ nationalité affiché reste du texte libre, la mannequin
// peut toujours l'écraser (née au Mali mais ivoirienne, par exemple).
function nationaliteSuggeree(libellePays, sexe) {
  const entree = PAYS_NAISSANCE.find(([libelle]) => libelle === libellePays);
  if (!entree) return '';
  return sexe === 'homme' ? entree[2] : entree[1];
}
